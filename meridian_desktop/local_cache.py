"""The local cache: Meridian's local MCP servers, written into the Claude Desktop and Codex user configs. Pure Python.

No Qt import. The desktop calls this at a real start (ui/app.py), so both apps keep the local servers when the tunnel or
the desktop is down. Only local stdio servers are written: no sign-in, no tunnel and no hosted URL. The servers are the
five groups in tool_catalog.py: code (codebase-memory-mcp and Serena), outputs, docs, latex and debug. chat-files, the
filesystem server, is never written.

Formats, confirmed from the vendor docs and from the Meridian core's meridian/client_setup.py on origin/dev:
- Claude Desktop: %APPDATA%\\Claude\\claude_desktop_config.json, JSON. Each server is mcpServers[name] = {command, args, env}.
  It has no per-tool filter, so a server with some tools off is written with all its tools, and the plan says so.
- Codex: ~/.codex/config.toml (CODEX_HOME moves the folder), TOML. Each server is [mcp_servers.<name>] with command,
  args, env and disabled_tools. disabled_tools is a deny list of tool names. enabled_tools (an allow list) is not used.

Every change is planned first. plan_local_cache is a dry run and writes nothing. write_plan backs up a changed file to
<name>.meridian-desktop-backup-<stamp>, writes the new text to a temp file in the same folder and replaces the file. It
refuses when the file changed after it was planned. A file that does not parse is refused and never rewritten.

Ownership. The server names are owned by this module, in both clients, and so is every name with the meridian-custom- prefix
(the owner's custom connectors, see custom_connectors.py). Codex entries are written in one managed block,
between MARK_BEGIN and MARK_END, which this module rewrites. A table for one of these names that already sits outside
that block (the core's client setup writes the same names) is left exactly as it is, and the plan says so. The core's
block is never edited, because its own apply removes and re-renders it. Claude Desktop entries are overwritten under
these names, as the core's client setup does. Every other key and table is compared before and after a write, and a
write that would change one is refused.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import sys
import tempfile
import time
import tomllib
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from meridian_desktop import tool_catalog

CLAUDE_DESKTOP = "claude-desktop"
CODEX = "codex"

SERENA_PACKAGE = "serena-agent==1.5.3"
# npx packages are pinned to an exact version. An unpinned package is downloaded and run again on every client
# launch, so a new release would change what runs with the owner's local access.
DEBUG_PACKAGE = "@debugmcp/mcp-debugger@0.26.0"
LATEX_PACKAGE = "@meridianmcp/mcp@0.1.9"
MARK_BEGIN = "# >>> meridian-desktop local cache (generated by Meridian Desktop; do not edit) >>>"
MARK_END = "# <<< meridian-desktop local cache <<<"
BACKUP_INFIX = ".meridian-desktop-backup-"

# The server order every plan and note follows.
SERVER_ORDER = ("codebase", "serena", "outputs", "docs", "latex", "debug")

# The name each client uses for each server. Claude Desktop names match the core's client setup. Codex names match it too,
# except Serena, which the core calls serena-local there.
NAMES: dict[str, dict[str, str]] = {
    CLAUDE_DESKTOP: {
        "codebase": "codebase-memory-mcp",
        "serena": "meridian-extract",
        "outputs": "meridian-outputs",
        "docs": "meridian-docs",
        "latex": "meridian-latex",
        "debug": "mcp-debugger",
    },
    CODEX: {
        "codebase": "codebase-memory-mcp",
        "serena": "serena-local",
        "outputs": "meridian-outputs",
        "docs": "meridian-docs",
        "latex": "meridian-latex",
        "debug": "mcp-debugger",
    },
}
# Serena's context follows the client, as in the core's client setup.
SERENA_CONTEXT = {CLAUDE_DESKTOP: "claude-code", CODEX: "codex"}
# The owner's custom connectors (custom_connectors.py) are written under this prefix. A name the owner gives can then never
# clash with a Meridian server, and any entry with the prefix is one this module owns, so one removed from the list is removed.
CUSTOM_PREFIX = "meridian-custom-"

_MANAGED_CODEX_KEYS = frozenset({"command", "args", "env", "enabled", "disabled_tools"})
_HEADER = re.compile(r"^\s*\[(?!\[)\s*([^\]]+?)\s*\]\s*(?:#.*)?$")
_BARE_KEY = re.compile(r"[A-Za-z0-9_-]+")
_BOM = "﻿"

Resolve = Callable[[str, tuple[Path, ...]], "str | None"]


class LocalCacheError(RuntimeError):
    """A config cannot be read or safely rewritten, or changed while it was being planned. Nothing is written."""


@dataclass(frozen=True)
class ServerSpec:
    """One local server as a client config holds it. ``server`` is the catalog id, ``name`` is the client's name."""

    server: str
    name: str
    command: str
    args: tuple[str, ...]
    env: Mapping[str, str] = field(default_factory=dict)

    def json_entry(self) -> dict:
        entry: dict = {"command": self.command, "args": list(self.args)}
        if self.env:
            entry["env"] = dict(self.env)
        return entry


@dataclass(frozen=True)
class CustomCache:
    """The owner's custom connectors for the cache: the stdio specs that resolved on this computer, and a note for each
    one left out. Built by custom_connectors.cache_entries. Empty means none is written."""

    specs: tuple[ServerSpec, ...] = ()
    notes: tuple[str, ...] = ()


@dataclass(frozen=True)
class FilePlan:
    """What one client config would become. ``text`` is what a write would put in the file, and ``source_text`` is what
    the file holds now (None when it does not exist). ``error`` is set when the file is refused, and then nothing is written.
    """

    client: str
    path: str
    source_text: str | None
    text: str
    added: tuple[str, ...] = ()
    updated: tuple[str, ...] = ()
    removed: tuple[str, ...] = ()
    unchanged: tuple[str, ...] = ()
    notes: tuple[str, ...] = ()
    error: str | None = None
    # Set when the app's own config folder is missing, so the app does not look set up on this computer. Nothing is created.
    skipped: str = ""

    @property
    def will_write(self) -> bool:
        return self.error is None and not self.skipped and self.text != (self.source_text or "")


@dataclass(frozen=True)
class LocalCachePlan:
    """The dry run for both clients. Building it writes nothing."""

    files: tuple[FilePlan, ...]

    @property
    def notes(self) -> tuple[str, ...]:
        # A note two clients share (a custom connector left out) is shown once.
        return tuple(dict.fromkeys(note for plan in self.files for note in plan.notes))


def find_command(name: str, fallbacks: tuple[Path, ...] = ()) -> str | None:
    """The path of a program on PATH, or one of the fallback files, or None when neither exists."""
    found = shutil.which(name)
    if found:
        return found
    for candidate in fallbacks:
        if candidate.is_file():
            return str(candidate)
    return None


def default_claude_desktop_config(env: Mapping[str, str] | None = None, platform: str | None = None) -> Path:
    """Claude Desktop's user config. On Windows it is %APPDATA%\\Claude\\claude_desktop_config.json."""
    source = os.environ if env is None else env
    current = sys.platform if platform is None else platform
    if current == "win32":
        appdata = str(source.get("APPDATA") or "").strip()
        base = Path(appdata) if appdata else Path.home() / "AppData" / "Roaming"
        return base / "Claude" / "claude_desktop_config.json"
    if current == "darwin":
        return Path.home() / "Library" / "Application Support" / "Claude" / "claude_desktop_config.json"
    return Path.home() / ".config" / "Claude" / "claude_desktop_config.json"


def default_codex_config(env: Mapping[str, str] | None = None) -> Path:
    """Codex's user config, ~/.codex/config.toml. CODEX_HOME, when set, is the folder instead."""
    source = os.environ if env is None else env
    home = str(source.get("CODEX_HOME") or "").strip()
    return (Path(home) if home else Path.home() / ".codex") / "config.toml"


def build_specs(client: str, core_checkout: str, resolve: Resolve, home: Path) -> tuple[dict[str, ServerSpec], list[str]]:
    """The local servers one client should have, with paths resolved on this computer, and a note for each one left out."""
    names = NAMES[client]
    specs: dict[str, ServerSpec] = {}
    notes: list[str] = []
    local_bin = home / ".local" / "bin"

    codebase = resolve("codebase-memory-mcp", (local_bin / "codebase-memory-mcp.exe", local_bin / "codebase-memory-mcp"))
    if codebase:
        specs["codebase"] = ServerSpec("codebase", names["codebase"], codebase, ("--ui=false",))
    else:
        notes.append(f"{names['codebase']} is not written: codebase-memory-mcp was not found on this computer.")

    uvx = resolve("uvx", (local_bin / "uvx.exe", local_bin / "uvx"))
    if uvx:
        specs["serena"] = ServerSpec(
            "serena",
            names["serena"],
            uvx,
            (
                "--python", "3.12", "--from", SERENA_PACKAGE, "serena", "start-mcp-server",
                "--context", SERENA_CONTEXT[client],
                "--enable-web-dashboard", "false",
                "--enable-gui-log-window", "false",
                "--open-web-dashboard", "false",
            ),
        )
    else:
        notes.append(f"{names['serena']} is not written: uvx was not found on this computer.")

    # outputs and docs run from the Meridian core checkout, so they need that folder to hold their extension.
    core = Path(core_checkout) if core_checkout else None
    for server, folder, module in (
        ("outputs", "meridian-outputs", "meridian-outputs-mcp"),
        ("docs", "meridian-docs", "meridian-docs-mcp"),
    ):
        if uvx is None:
            notes.append(f"{names[server]} is not written: uvx was not found on this computer.")
        elif core is None or not (core / "extensions" / folder).is_dir():
            notes.append(
                f"{names[server]} is not written: the Meridian core checkout is not set, or has no extensions/{folder}."
            )
        else:
            specs[server] = ServerSpec(server, names[server], uvx, ("--from", str(core / "extensions" / folder), module))

    npx = resolve("npx", ())
    if npx is None:
        for server in ("debug", "latex"):
            notes.append(f"{names[server]} is not written: npx was not found on this computer.")
    else:
        specs["debug"] = ServerSpec("debug", names["debug"], "npx", ("-y", DEBUG_PACKAGE))
        specs["latex"] = ServerSpec(
            "latex", names["latex"], "npx", ("-y", "--package", LATEX_PACKAGE, "meridian-latex", "mcp")
        )
    return specs, notes


def _owned_names(client: str, existing: Iterable[str]) -> set[str]:
    """The names this module owns in one client: the Meridian servers, and every custom connector name already there."""
    return {NAMES[client][server] for server in SERVER_ORDER} | {name for name in existing if name.startswith(CUSTOM_PREFIX)}


def _server_names(document: Mapping) -> Iterable[str]:
    """The names in a parsed Codex config's mcp_servers table, or nothing when the table is absent or not a table."""
    servers = document.get("mcp_servers")
    return servers.keys() if isinstance(servers, dict) else ()


def _wanted(
    client: str, specs: Mapping[str, ServerSpec], disabled: Iterable[str], custom: CustomCache
) -> tuple[dict[str, tuple[ServerSpec, tuple[str, ...]]], list[str]]:
    """The servers to write, each with its switched-off tool names, plus the notes for servers left out."""
    off = tool_catalog.normalise(disabled)
    wanted: dict[str, tuple[ServerSpec, tuple[str, ...]]] = {}
    notes: list[str] = []
    for server in SERVER_ORDER:
        spec = specs.get(server)
        if spec is None:
            continue
        disabled_names = tool_catalog.server_disabled_tools(server, off)
        total = len(tool_catalog.server_tools(server))
        if total and len(disabled_names) == total:
            notes.append(f"{spec.name} is not written: every one of its tools is switched off in Meridian Desktop.")
            continue
        if client == CLAUDE_DESKTOP and disabled_names:
            notes.append(
                f"{spec.name} is written with all {total} tools. Claude Desktop cannot hide single tools, so "
                f"{len(disabled_names)} tool(s) switched off in Meridian Desktop stay available there."
            )
        wanted[server] = (spec, disabled_names)
    for spec in custom.specs:
        wanted[spec.server] = (spec, ())
    return wanted, notes


def _read(path: Path) -> str | None:
    """The file's exact text. Read as bytes, so a CRLF line ending is kept and not turned into LF on Windows."""
    return path.read_bytes().decode("utf-8") if path.exists() else None


def _missing_folder(client: str, path: Path, source: str | None, require_folder: bool, notes: list[str]) -> FilePlan | None:
    """A skipped plan when the app's folder is missing and a new file would be needed there, else None."""
    if source is not None or not require_folder or path.parent.is_dir():
        return None
    name = "Claude Desktop" if client == CLAUDE_DESKTOP else "Codex"
    return FilePlan(
        client=client,
        path=str(path),
        source_text=None,
        text="",
        notes=tuple(notes),
        skipped=f"{name} does not look set up on this computer: its folder {path.parent} does not exist",
    )


def plan_claude_desktop(
    path: Path,
    *,
    disabled: Iterable[str] = (),
    core_checkout: str = "",
    resolve: Resolve = find_command,
    home: Path | None = None,
    require_folder: bool = True,
    custom: CustomCache = CustomCache(),
) -> FilePlan:
    """The Claude Desktop change for ``path``, as a dry run. Writes nothing.

    With ``require_folder`` (the default at a real start), a missing folder means the app is not set up here, so no file is
    created in it.
    """
    home = Path.home() if home is None else home
    specs, build_notes = build_specs(CLAUDE_DESKTOP, core_checkout, resolve, home)
    wanted, notes = _wanted(CLAUDE_DESKTOP, specs, disabled, custom)
    notes = build_notes + notes + list(custom.notes)
    source = _read(path)
    skipped = _missing_folder(CLAUDE_DESKTOP, path, source, require_folder, notes)
    if skipped is not None:
        return skipped
    text = source or ""
    bom = text.startswith(_BOM)
    body = text[1:] if bom else text
    wanted_by_name = {spec.name: spec.json_entry() for spec, _ in wanted.values()}

    try:
        document = json.loads(body) if body.strip() else {}
    except ValueError as exc:
        return _refused(CLAUDE_DESKTOP, path, source, f"{path} is not valid JSON; refusing to rewrite it ({exc})", notes)
    if not isinstance(document, dict):
        return _refused(CLAUDE_DESKTOP, path, source, f"{path} does not hold a JSON object; refusing to rewrite it", notes)
    current = document.get("mcpServers")
    if current is None:
        current = {}
    if not isinstance(current, dict):
        return _refused(CLAUDE_DESKTOP, path, source, f"{path} has a non-object mcpServers value; refusing to rewrite it", notes)

    # The names being written count as owned too, so a custom entry that is not in the file yet is not refused as foreign.
    owned = _owned_names(CLAUDE_DESKTOP, [*current, *wanted_by_name])

    merged: dict = {}
    for name, value in current.items():
        if name not in owned:
            merged[name] = value
        elif name in wanted_by_name:
            merged[name] = wanted_by_name[name]
    for name, entry in wanted_by_name.items():
        merged.setdefault(name, entry)

    new_document = dict(document)
    if merged or "mcpServers" in document:
        new_document["mcpServers"] = merged
    if new_document == document:
        new_text = text
    else:
        new_text = (_BOM if bom else "") + json.dumps(new_document, indent=2, ensure_ascii=False) + "\n"

    added = tuple(sorted(n for n in wanted_by_name if n not in current))
    updated = tuple(sorted(n for n in wanted_by_name if n in current and current[n] != wanted_by_name[n]))
    removed = tuple(sorted(n for n in owned if n in current and n not in wanted_by_name))
    unchanged = tuple(sorted(n for n in wanted_by_name if n in current and current[n] == wanted_by_name[n]))
    return FilePlan(
        client=CLAUDE_DESKTOP,
        path=str(path),
        source_text=source,
        text=new_text,
        added=added,
        updated=updated,
        removed=removed,
        unchanged=unchanged,
        notes=tuple(notes),
    )


def _refused(client: str, path: Path, source: str | None, error: str, notes: list[str]) -> FilePlan:
    return FilePlan(client=client, path=str(path), source_text=source, text=source or "", notes=tuple(notes), error=error)


def _toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _toml_key(key: str) -> str:
    return key if _BARE_KEY.fullmatch(key) else _toml_string(key)


def _owned_headers(lines: list[str], owned: set[str]) -> set[str]:
    """The owned names whose main [mcp_servers.<name>] header appears in ``lines``."""
    targets = {f"mcp_servers.{name}": name for name in owned}
    found: set[str] = set()
    for line in lines:
        match = _HEADER.match(line)
        if match and match.group(1).replace(" ", "") in targets:
            found.add(targets[match.group(1).replace(" ", "")])
    return found


def _preserved_keys(lines: list[str], owned: set[str]) -> dict[str, list[str]]:
    """Per owned name, the key lines of its main table that this module does not manage (a cwd, a timeout).

    They are carried over into the rewritten block, so an owner's own key is kept.
    """
    targets = {f"mcp_servers.{name}": name for name in owned}
    preserved: dict[str, list[str]] = {}
    current: str | None = None
    for line in lines:
        match = _HEADER.match(line)
        if match:
            current = targets.get(match.group(1).replace(" ", ""))
            continue
        if current is None:
            continue
        key = line.split("=", 1)[0].strip() if "=" in line else ""
        if key and key not in _MANAGED_CODEX_KEYS and not key.startswith("#"):
            preserved.setdefault(current, []).append(line.rstrip())
    return preserved


def _split_managed_block(lines: list[str]) -> tuple[list[str], list[str]]:
    """(lines outside the block, lines of the block). Raises when the markers are unpaired or repeated."""
    begins = [i for i, line in enumerate(lines) if line.strip() == MARK_BEGIN]
    ends = [i for i, line in enumerate(lines) if line.strip() == MARK_END]
    if not begins and not ends:
        return list(lines), []
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise LocalCacheError("the Meridian Desktop block markers in Codex config are damaged; refusing to rewrite it")
    start, stop = begins[0], ends[0]
    return lines[:start] + lines[stop + 1 :], lines[start : stop + 1]


def _trim_trailing_blank(lines: list[str]) -> list[str]:
    while lines and not lines[-1].strip():
        lines = lines[:-1]
    return lines


def _render_codex_block(rendered: list[tuple[ServerSpec, tuple[str, ...]]], preserved: dict[str, list[str]]) -> list[str]:
    lines = [MARK_BEGIN]
    for spec, disabled_names in rendered:
        lines.append(f"[mcp_servers.{spec.name}]")
        lines.append(f"command = {_toml_string(spec.command)}")
        lines.append("args = [" + ", ".join(_toml_string(arg) for arg in spec.args) + "]")
        if spec.env:
            pairs = ", ".join(f"{_toml_key(k)} = {_toml_string(v)}" for k, v in spec.env.items())
            lines.append("env = { " + pairs + " }")
        if disabled_names:
            lines.append("disabled_tools = [" + ", ".join(_toml_string(tool) for tool in disabled_names) + "]")
        lines.extend(preserved.get(spec.name, []))
        lines.append("")
    lines.append(MARK_END)
    return lines


def plan_codex(
    path: Path,
    *,
    disabled: Iterable[str] = (),
    core_checkout: str = "",
    resolve: Resolve = find_command,
    home: Path | None = None,
    require_folder: bool = True,
    custom: CustomCache = CustomCache(),
) -> FilePlan:
    """The Codex change for ``path``, as a dry run. Writes nothing. ``require_folder`` as for plan_claude_desktop."""
    home = Path.home() if home is None else home
    specs, build_notes = build_specs(CODEX, core_checkout, resolve, home)
    wanted, notes = _wanted(CODEX, specs, disabled, custom)
    notes = build_notes + notes + list(custom.notes)
    source = _read(path)
    skipped = _missing_folder(CODEX, path, source, require_folder, notes)
    if skipped is not None:
        return skipped
    text = source or ""
    bom = text.startswith(_BOM)
    body = text[1:] if bom else text
    eol = "\r\n" if "\r\n" in body else "\n"

    try:
        old_document = tomllib.loads(body) if body.strip() else {}
    except tomllib.TOMLDecodeError as exc:
        return _refused(CODEX, path, source, f"{path} is not valid TOML; refusing to rewrite it ({exc})", notes)

    try:
        outside, old_block = _split_managed_block(body.splitlines())
    except LocalCacheError as exc:
        return _refused(CODEX, path, source, str(exc), notes)

    # The names being written count as owned too, so a custom entry that is not in the file yet is not refused as foreign.
    owned = _owned_names(CODEX, [*_server_names(old_document), *(spec.name for spec, _ in wanted.values())])
    foreign = _owned_headers(outside, owned)
    preserved = _preserved_keys(old_block, owned)
    rendered: list[tuple[ServerSpec, tuple[str, ...]]] = [
        entry for entry in wanted.values() if entry[0].name not in foreign
    ]
    rendered_names = {spec.name for spec, _ in rendered}
    for name in sorted(owned):
        if name in foreign and name not in rendered_names:
            notes.append(f"{name} is left as it is: it is set outside the Meridian Desktop block (Client setup).")

    block = _render_codex_block(rendered, preserved) if rendered else []
    kept = _trim_trailing_blank(outside)
    new_lines = kept + ([""] if kept and block else []) + block
    eol_joined = eol.join(new_lines) + eol if new_lines else ""
    new_body = eol_joined

    try:
        new_document = tomllib.loads(new_body) if new_body.strip() else {}
    except tomllib.TOMLDecodeError as exc:
        return _refused(CODEX, path, source, f"rendering the Codex config would not parse ({exc}); nothing was written", notes)

    error = _validate_codex(old_document, new_document, owned, foreign, {spec.name for spec, _ in rendered}, preserved)
    if error:
        return _refused(CODEX, path, source, error, notes)

    new_text = (_BOM if bom else "") + new_body
    if new_body == body:
        new_text = text

    old_servers = old_document.get("mcp_servers") or {}
    new_servers = new_document.get("mcp_servers") or {}
    added = tuple(sorted(n for n in owned if n in new_servers and n not in old_servers))
    updated = tuple(sorted(n for n in owned if n in new_servers and n in old_servers and new_servers[n] != old_servers[n]))
    removed = tuple(sorted(n for n in owned if n in old_servers and n not in new_servers and n not in foreign))
    unchanged = tuple(sorted(n for n in owned if n in new_servers and n in old_servers and new_servers[n] == old_servers[n]))
    return FilePlan(
        client=CODEX,
        path=str(path),
        source_text=source,
        text=new_text,
        added=added,
        updated=updated,
        removed=removed,
        unchanged=unchanged,
        notes=tuple(notes),
    )


def _validate_codex(
    old: dict,
    new: dict,
    owned: set[str],
    foreign: set[str],
    rendered: set[str],
    preserved: dict[str, list[str]],
) -> str | None:
    """None when the rendering is safe. Otherwise the reason it is refused. Unowned parts must be unchanged."""
    for key in set(old) | set(new):
        if key != "mcp_servers" and old.get(key) != new.get(key):
            return f"rendering would change the top-level key '{key}' in Codex config; nothing was written"
    old_servers = old.get("mcp_servers") or {}
    new_servers = new.get("mcp_servers") or {}
    for name in set(old_servers) | set(new_servers):
        if name in owned:
            if name in rendered:
                old_rest = {k: v for k, v in (old_servers.get(name) or {}).items() if k not in _MANAGED_CODEX_KEYS}
                new_rest = {k: v for k, v in (new_servers.get(name) or {}).items() if k not in _MANAGED_CODEX_KEYS}
                if old_rest != new_rest:
                    return (
                        f"owned server '{name}' has settings this module does not manage "
                        f"({', '.join(sorted(old_rest))}); nothing was written"
                    )
            continue
        if old_servers.get(name) != new_servers.get(name):
            return f"rendering would change the unowned MCP server '{name}' in Codex config; nothing was written"
    return None


def write_plan(plan: FilePlan) -> str | None:
    """Back up the file, then replace it atomically with the planned text. Returns the backup path, or None.

    Refuses when the plan is refused, or when the file changed since it was planned. Writes nothing when the plan
    would change nothing.
    """
    if plan.error is not None:
        raise LocalCacheError(plan.error)
    if plan.skipped:
        return None
    path = Path(plan.path)
    if _read(path) != plan.source_text:
        raise LocalCacheError(f"{path} changed while the local cache was planned; nothing was written. Start again.")
    if not plan.will_write:
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = _backup(path)
    _atomic_write(path, plan.text)
    return backup


def _backup(path: Path) -> str | None:
    if not path.exists():
        return None
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    candidate = path.with_name(f"{path.name}{BACKUP_INFIX}{stamp}")
    counter = 1
    while candidate.exists():
        counter += 1
        candidate = path.with_name(f"{path.name}{BACKUP_INFIX}{stamp}-{counter}")
    shutil.copy2(path, candidate)
    return str(candidate)


def _atomic_write(path: Path, text: str) -> None:
    fd, tmp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".meridian-desktop-tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        _replace_with_retry(tmp_name, path)
    except BaseException:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass
        raise


REPLACE_ATTEMPTS = 20
REPLACE_WAIT_SECONDS = 0.05


def _replace_with_retry(source: str, target: Path) -> None:
    """Replace ``target``, waiting out a brief Windows file lock. Any other error is raised unchanged."""
    for attempt in range(REPLACE_ATTEMPTS):
        try:
            os.replace(source, target)
            return
        except PermissionError:
            if attempt == REPLACE_ATTEMPTS - 1:
                raise
            time.sleep(REPLACE_WAIT_SECONDS)


def plan_local_cache(
    *,
    disabled: Iterable[str] = (),
    claude_path: Path | None = None,
    codex_path: Path | None = None,
    core_checkout: str = "",
    resolve: Resolve = find_command,
    home: Path | None = None,
    require_folder: bool = True,
    custom: CustomCache = CustomCache(),
) -> LocalCachePlan:
    """The dry run for both clients. Writes nothing. Pass explicit paths to keep tests out of the real configs."""
    claude = claude_path if claude_path is not None else default_claude_desktop_config()
    codex = codex_path if codex_path is not None else default_codex_config()
    return LocalCachePlan(
        files=(
            plan_claude_desktop(
                claude,
                disabled=disabled,
                core_checkout=core_checkout,
                resolve=resolve,
                home=home,
                require_folder=require_folder,
                custom=custom,
            ),
            plan_codex(
                codex,
                disabled=disabled,
                core_checkout=core_checkout,
                resolve=resolve,
                home=home,
                require_folder=require_folder,
                custom=custom,
            ),
        )
    )


def apply_local_cache(plan: LocalCachePlan) -> list[str]:
    """Write every planned change. Returns one plain line per file. A refused or changed file is reported, not raised."""
    lines: list[str] = []
    for file_plan in plan.files:
        label = "Claude Desktop" if file_plan.client == CLAUDE_DESKTOP else "Codex"
        if file_plan.skipped:
            lines.append(f"{label}: not written ({file_plan.skipped}).")
            continue
        try:
            backup = write_plan(file_plan)
        except (LocalCacheError, OSError) as exc:
            lines.append(f"{label}: not written ({exc.__class__.__name__}: {_plain(exc)}).")
            continue
        if backup is None and not file_plan.will_write:
            lines.append(f"{label}: already up to date ({file_plan.path}).")
        else:
            lines.append(f"{label}: written to {file_plan.path}; backup at {backup or 'none (new file)'}.")
    return lines


def _plain(exc: BaseException) -> str:
    return str(exc) if isinstance(exc, LocalCacheError) else "the file could not be written"


def sync_local_cache(
    *,
    disabled: Iterable[str] = (),
    claude_path: Path | None = None,
    codex_path: Path | None = None,
    core_checkout: str = "",
    resolve: Resolve = find_command,
    home: Path | None = None,
    require_folder: bool = True,
    custom: CustomCache = CustomCache(),
) -> list[str]:
    """Plan, then write, both clients. Returns the plain lines to log."""
    plan = plan_local_cache(
        disabled=disabled,
        claude_path=claude_path,
        codex_path=codex_path,
        core_checkout=core_checkout,
        resolve=resolve,
        home=home,
        require_folder=require_folder,
        custom=custom,
    )
    return list(plan.notes) + apply_local_cache(plan)


